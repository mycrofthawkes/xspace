/*
Что происходит «под капотом»:

    int age{25};

1. Компилятор знает тип объекта — int.
2. Для объекта предусматривается достаточно памяти.
3. Битовое представление числа 25 становится значением объекта.
4. Имя age позволяет обращаться к нему в исходном коде.

Однако оптимизатор может хранить значение в регистре процессора
или вообще вычислить результат заранее. C++ описывает поведение
абстрактной машины, а компилятор выбирает эффективную реализацию.

Важно:

sizeof(char) всегда равен 1, но один байт C++ не обязан состоять
ровно из восьми бит. На современных компьютерах обычно это 8 бит.
Размер int стандартом точно не зафиксирован, хотя чаще всего он
занимает 4 байта.
*/